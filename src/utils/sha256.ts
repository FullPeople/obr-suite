// Minimal synchronous SHA-256 → lowercase hex.
//
// Exists because resource-id repair runs INSIDE OBR.scene.items
// updateItems mutators, which are synchronous — crypto.subtle.digest is
// async and cannot be used there. Digests must match Python's
// hashlib.sha256(name.encode("utf-8")).hexdigest() so client-repaired
// ids equal the card server's canonical ids for the same name.

