import {build} from 'rolldown';
import {mkdirSync,writeFileSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {execFileSync} from 'node:child_process';
const out=resolve('../suite-results');mkdirSync(out,{recursive:true});
const source=resolve('tools/feedback196-test-entry.ts');
writeFileSync(source,`import assert from 'node:assert/strict';
import {evaluateStatExpression as calc} from '../src/utils/statExpression';
import {resolveVisionSource,VISION_KEY,CARD_BIND_KEY} from '../src/modules/fullFog/dynfog/light/visionPolicy';
import {playerOperable,playerVisible,blocksVision} from '../src/modules/fullFog/dynfog/opening/types';
import {readOpenings,serialiseOpenings,openingsSignature} from '../src/modules/fullFog/dynfog/opening/read';
import {OPENINGS_KEY} from '../src/modules/fullFog/dynfog/ids';
import {createGame,projectOmniscient,projectPublic} from '../extensions/three-dragon-ante/src/game/rules';
let checks=0;const equal=(actual,expected)=>{assert.deepEqual(actual,expected);checks++};
for(const [text,current,expected] of [['-2*3',20,14],['/2',21,10],['2*(3+4)',20,14],['=(20-2)/3',99,6],['+2*(3+1)',10,18],['1/0',10,null],['Math.max(1,2)',10,null],['1+2foo',10,null],['1;globalThis.pwned=true',1,null],['--2',10,12]])equal(calc(text,current),expected);
const context={playerId:'pl',playerIds:new Set(['pl']),cards:new Map()};
const token={id:'token',createdUserId:'gm',type:'IMAGE',layer:'CHARACTER',visible:true,metadata:{}};
const vision=(item)=>resolveVisionSource(item,context,()=>null);
equal(vision(token).team,true);equal(vision(token).personal,false);
equal(vision({...token,metadata:{[VISION_KEY]:{mode:'gm'}}}).team,false);
equal(vision({...token,metadata:{[VISION_KEY]:{mode:'owners',ownerIds:[]}}}).team,false);
equal(vision({...token,visible:false}).visible,false);
context.cards.set('private',{ownerIds:['pl'],visibility:'dm'});
equal(vision({...token,metadata:{[CARD_BIND_KEY]:'private'}}).team,false);
equal(vision({...token,metadata:{'com.bestiary/slug':'MM~Goblin'}}).team,true);
const door={id:'door',kind:'locked',open:false,polyIndex:0,t1:.2,t2:.4};
equal(playerVisible(door),true);equal(playerOperable(door),false);equal(blocksVision(door),true);equal(blocksVision({...door,open:true}),false);
equal(readOpenings({...token,metadata:{[OPENINGS_KEY]:serialiseOpenings([door])}})[0],door);
assert.notEqual(openingsSignature([door]),openingsSignature([{...door,kind:'door'}]));checks++;
const game=createGame({id:'spectator',seats:[{id:'a',name:'A'},{id:'b',name:'B'}],seed:42});
const view=projectOmniscient(game,'');equal(view.selfSeatId,'');equal(view.hand,[]);equal(Object.keys(view.privateHands),['a','b']);equal('privateHands' in projectPublic(game),false);
console.log(JSON.stringify({checks,passed:true,realRoomVerified:false}));
`);
await build({input:source,platform:'node',output:{file:join(out,'feedback196-test.mjs'),format:'esm',codeSplitting:false},logLevel:'silent'});
execFileSync(process.execPath,[join(out,'feedback196-test.mjs')],{stdio:'inherit'});
