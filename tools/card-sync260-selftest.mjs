const body=ts.transpileModule(`let chosen='card:original';return {handle:async m=>{${handler}},current:()=>chosen};`,{compilerOptions:{target:ts.ScriptTarget.ES2022}}).outputText;
const factory=Function('getState','relay','playerId','OBR','DIRECTORY','LIST','cacheDocument',body);
const host=factory(()=>({enabled:{characterCards:true}}),relay,'player',OBR,'cards','scene-cards',(key,data)=>documents.set(key,structuredClone(data)));
const old={schema_version:'0.3',dnd_card_web:{schemaVersion:1},identity:{character_name:'Before sync backup'},core_stats:{hp:{current:3,max:20}}};
const result=await host.handle({type:'createCard',data:old,select:false});
