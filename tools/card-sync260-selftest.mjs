import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';

const source=readFileSync(new URL('../src/workbench/background.ts',import.meta.url),'utf8');
const start=source.indexOf("if(m.type==='createCard'){");
const end=source.indexOf("if(m.type==='rules')",start);
assert(start>=0&&end>start,'Actual host creation handler must be present');
const handler=source.slice(start,end);
const original={id:'original',name:'Bound original',owner_ids:['player'],visibility:'public',locked:false};
let writes=0,fail=false;
const metadata={'cards':[original]};
const OBR={room:{id:'room',getMetadata:async()=>structuredClone(metadata),setMetadata:async data=>{Object.assign(metadata,data);writes++;}},scene:{isReady:async()=>false},broadcast:{sendMessage:async()=>{}}};
